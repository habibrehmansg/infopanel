using System.Net;
using System.Net.Http.Headers;
using System.Text.Json;
using InfoPanel.Spec;
using Xunit;
using static InfoPanel.Tests.ReadEndpointTests;

namespace InfoPanel.Tests;

/// <summary>
/// <c>POST /api/blobs</c> streams its body to disk (spec/docs/api.md, "Blobs"): up to <c>videoBytes</c>, written as it
/// arrives, a body over it refused with 413 and nothing stored, a picture over <c>mediaBytes</c> stored and refused as
/// media, a video described by its container.
/// </summary>
public class BlobUploadTests(EngineFactory factory) : IClassFixture<EngineFactory>
{
    private static CancellationToken Ct => TestContext.Current.CancellationToken;

    private string Blobs => Path.Combine(factory.DataDir, "blobs");

    private string[] BlobFiles() => Directory.Exists(Blobs) ? Directory.GetFiles(Blobs).Select(Path.GetFileName).Order().ToArray()! : [];

    /// <summary>
    /// A body of <paramref name="length"/> generated bytes, written in chunks, with or without a declared length; it
    /// can wait at <paramref name="pauseAt"/> bytes until <paramref name="resume"/> completes.
    /// </summary>
    internal sealed class GeneratedContent(long length, bool declareLength, long pauseAt = -1, TaskCompletionSource? paused = null,
        Task? resume = null) : HttpContent
    {
        public long Written { get; private set; }

        protected override async Task SerializeToStreamAsync(Stream stream, TransportContext? context)
        {
            var chunk = new byte[256 * 1024];
            while (Written < length)
            {
                if (Written == pauseAt && resume is not null)
                {
                    await stream.FlushAsync();
                    paused!.TrySetResult();
                    await resume;
                }
                var n = (int)Math.Min(chunk.Length, length - Written);
                if (pauseAt > Written) n = (int)Math.Min(n, pauseAt - Written);
                await stream.WriteAsync(chunk.AsMemory(0, n));
                Written += n;
            }
        }

        protected override bool TryComputeLength(out long length1)
        {
            length1 = length;
            return declareLength;
        }
    }

    private async Task<HttpResponseMessage> Post(HttpContent content)
    {
        using var api = factory.CreateApiClient();
        return await api.PostAsync("/api/blobs", content, Ct);
    }

    [Fact]
    public async Task ABodyOverVideoBytes_Streamed_Is413_AndNothingIsStored()
    {
        var before = BlobFiles();
        using var response = await Post(new GeneratedContent(SpecLimits.Default.VideoBytes + 1L, declareLength: false));
        Assert.Equal(HttpStatusCode.RequestEntityTooLarge, response.StatusCode);
        Assert.Equal(before, BlobFiles());
    }

    [Fact]
    public async Task ABodyDeclaredOverVideoBytes_Is413_BeforeItIsRead()
    {
        var before = BlobFiles();
        var content = new GeneratedContent(SpecLimits.Default.VideoBytes + 1L, declareLength: true);
        using var response = await Post(content);
        Assert.Equal(HttpStatusCode.RequestEntityTooLarge, response.StatusCode);
        Assert.Equal(before, BlobFiles());
    }

    [Fact]
    public async Task APictureOverMediaBytes_IsStored_AndRefusedAsMedia()
    {
        var bytes = new byte[SpecLimits.Default.MediaBytes + 1];
        using var response = await Post(new ByteArrayContent(bytes));
        Assert.Equal(HttpStatusCode.Created, response.StatusCode);
        var info = JsonDocument.Parse(await response.Content.ReadAsStringAsync(Ct)).RootElement;
        Assert.True(Valid(info, "blobInfoMediaError"));
        Assert.Equal("limit.mediaBytes", info.GetProperty("mediaError").GetProperty("code").GetString());
        Assert.Equal(bytes.Length, info.GetProperty("bytes").GetInt64());
    }

    [Fact]
    public async Task AVideo_IsDescribedByItsContainer()
    {
        var video = VideoFixture.Read("clip-vp9.webm");
        using var response = await Post(new ByteArrayContent(video));
        Assert.True(response.StatusCode is HttpStatusCode.Created or HttpStatusCode.OK);
        var info = JsonDocument.Parse(await response.Content.ReadAsStringAsync(Ct)).RootElement;
        Assert.True(Valid(info, "blobInfoMedia"));
        var media = info.GetProperty("media");
        Assert.Equal(("matroska", "vp9", 64, 48), (media.GetProperty("format").GetString(), media.GetProperty("codec").GetString(),
            media.GetProperty("width").GetInt32(), media.GetProperty("height").GetInt32()));
    }

    [Fact]
    public async Task TheBody_IsWrittenToDiskAsItArrives()
    {
        var paused = new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously);
        var resume = new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously);
        const long half = 4 * 1024 * 1024;
        var content = new GeneratedContent(2 * half, declareLength: false, pauseAt: half, paused, resume.Task);
        var posting = Post(content);
        await paused.Task.WaitAsync(TimeSpan.FromSeconds(30), Ct);

        // With half the body sent and the rest held back, the half is in the upload's temp file already.
        long onDisk = 0;
        var deadline = DateTime.UtcNow.AddSeconds(30);
        while (DateTime.UtcNow < deadline && onDisk < half)
        {
            onDisk = Directory.Exists(Blobs) ? Directory.GetFiles(Blobs, "upload.*.tmp").Select(f => new FileInfo(f).Length).DefaultIfEmpty(0).Max() : 0;
            if (onDisk < half) await Task.Delay(20, Ct);
        }
        resume.SetResult();
        using var response = await posting;
        Assert.Equal(half, onDisk);
        Assert.Equal(HttpStatusCode.Created, response.StatusCode);
        Assert.Empty(Directory.GetFiles(Blobs, "*.tmp"));
    }
}

/// <summary>The Core tests' video fixtures (<c>InfoPanel.Core.Tests/Fixtures/video</c>, made by native/ffmpeg/make-fixtures.sh).</summary>
internal static class VideoFixture
{
    /// <summary>The fixture folder, found above the test's output folder (the repository's checkout).</summary>
    public static string Folder { get; } = Find(Path.Combine("InfoPanel.Core.Tests", "Fixtures", "video"));

    public static byte[] Read(string name) => File.ReadAllBytes(Path.Combine(Folder, name));

    private static string Find(string relative)
    {
        for (var dir = new DirectoryInfo(AppContext.BaseDirectory); dir is not null; dir = dir.Parent)
        {
            var path = Path.Combine(dir.FullName, relative);
            if (Directory.Exists(path)) return path;
        }
        throw new DirectoryNotFoundException($"{relative} not found above {AppContext.BaseDirectory}");
    }
}
