test('--check: 0 when equal, 1 (and writes nothing) when different or missing', () => {
  withScratch((dir) => {
    const out = join(dir, 'types.d.ts');
    assert.equal(cli('--schemas', schemaDir, '--out', out, '--check').status, 1, 'missing file differs');
    assert.equal(existsSync(out), false, '--check must not create the file');

    copyFileSync(expectedPath, out);
    const same = cli('--schemas', schemaDir, '--out', out, '--check');
    assert.equal(same.status, 0, same.stderr);

    const changed = readFileSync(out, 'utf8').replace('export type Level = 0 | 1 | 2;', 'export type Level = 0 | 1;');
    writeFileSync(out, changed);
    const diff = cli('--schemas', schemaDir, '--out', out, '--check');
    assert.equal(diff.status, 1);
    assert.match(diff.stderr, /types\.d\.ts/);
    assert.match(diff.stderr, /first difference at line \d+/);
    assert.equal(readFileSync(out, 'utf8'), changed, '--check must not rewrite the file');
    unlinkSync(out);
  });
});

