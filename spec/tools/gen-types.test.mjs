const cli = (...args) => spawnSync(process.execPath, [tool, ...args], { encoding: 'utf8' });

/** Runs `fn(dir)` in a scratch folder; removes its files afterwards. */
function withScratch(fn) {
  const dir = mkdtempSync(join(tmpdir(), 'gen-types-'));
  try {
    return fn(dir);
  } finally {
    for (const f of readdirSync(dir)) unlinkSync(join(dir, f));
    rmdirSync(dir);
  }
}

/** Writes `{ name: json }` as schema files into a scratch `schemas` folder and runs the CLI on it. */
function runCli(files, extra = []) {
  return withScratch((dir) => {
    const sdir = join(dir, 's');
    mkdirSync(sdir);
    for (const [name, json] of Object.entries(files)) writeFileSync(join(sdir, name), JSON.stringify(json));
    const out = join(dir, 'out.d.ts');
    const r = cli('--schemas', sdir, '--out', out, ...extra);
    const wrote = existsSync(out);
    for (const name of Object.keys(files)) unlinkSync(join(sdir, name));
    rmdirSync(sdir);
    return { ...r, wrote };
  });
}

