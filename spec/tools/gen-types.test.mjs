import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmdirSync, unlinkSync, writeFileSync, copyFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { generate } from './gen-types.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const tool = join(root, 'tools', 'gen-types.mjs');
const fixtures = join(root, 'tools', 'fixtures');
const schemaDir = join(fixtures, 'schemas');
const expectedPath = join(fixtures, 'expected.d.ts');
// A TypeScript compiler to type-check the generated fixture types with (optional): TSC=path/to/tsc.
const TSC = process.env.TSC ?? '';

const loadFixtures = () =>
  readdirSync(schemaDir)
    .filter((f) => f.endsWith('.schema.json'))
    .sort()
    .map((file) => ({ file, json: JSON.parse(readFileSync(join(schemaDir, file), 'utf8')) }));

const cli = (...args) => spawnSync(process.execPath, [tool, ...args], { encoding: 'utf8' });

/** Runs `fn(dir)` in a scratch folder; removes its files afterwards. */
function withScratch(fn) {
  const dir = mkdtempSync(join(tmpdir(), 'gen-types-'));
  try {
    return fn(dir);
  } finally {
    for (const f of readdirSync(dir)) unlinkSync(join(dir, f));
    rmdirSync(dir);
  }
}

/** Writes `{ name: json }` as schema files into a scratch `schemas` folder and runs the CLI on it. */
function runCli(files, extra = []) {
  return withScratch((dir) => {
    const sdir = join(dir, 's');
    mkdirSync(sdir);
    for (const [name, json] of Object.entries(files)) writeFileSync(join(sdir, name), JSON.stringify(json));
    const out = join(dir, 'out.d.ts');
    const r = cli('--schemas', sdir, '--out', out, ...extra);
    const wrote = existsSync(out);
    for (const name of Object.keys(files)) unlinkSync(join(sdir, name));
    rmdirSync(sdir);
    return { ...r, wrote };
  });
}

const schema = (id, rest) => ({ $id: id, ...rest });

test('fixtures generate exactly expected.d.ts', () => {
  assert.equal(generate(loadFixtures()), readFileSync(expectedPath, 'utf8'));
});

test('output has the header, LF endings, a trailing newline and no tabs', () => {
  const out = generate(loadFixtures());
  assert.ok(out.startsWith('// Generated by tools/gen-types.mjs from schemas/*.schema.json. Do not edit; run `npm run gen`.\n\nexport type JsonValue = '));
  assert.ok(out.endsWith('\n') && !out.endsWith('\n\n'));
  assert.ok(!out.includes('\r') && !out.includes('\t'));
});

test('deterministic: same input, same bytes, whatever the input order', () => {
  const files = loadFixtures();
  const a = generate(files);
  assert.equal(generate(files), a);
  assert.equal(generate([...files].reverse()), a);
  assert.equal(generate(JSON.parse(JSON.stringify(files))), a);
});

test('rules, one by one', () => {
  const out = generate([
    { file: 'a.schema.json', json: schema('urn:t:a:1', { $defs: {
      kinds: { enum: ['a', 1, true, null] },
      pt: { type: 'array', prefixItems: [{ type: 'number' }, { type: 'string' }, { type: 'boolean' }], minItems: 1 },
      loose: { type: 'array' },
      u: { type: 'array', items: { anyOf: [{ type: 'string' }, { type: 'null' }] } },
      both: { allOf: [{ type: 'string' }, { enum: ['x', 'y'] }] },
      noProps: { type: 'object' },
      closed: { type: 'object', properties: { a: { type: 'string' } }, required: ['a'], additionalProperties: false },
      t: { type: ['string', 'integer'] },
      bare: { type: 'object', oneOf: [{ type: 'string' }, { type: 'number' }] },
    } }) },
  ]);
  assert.match(out, /export type Kinds = "a" \| 1 \| true \| null;/);
  assert.match(out, /export type Pt = \[number, string\?, boolean\?\];/);
  assert.match(out, /export type Loose = JsonValue\[\];/);
  assert.match(out, /export type U = \(string \| null\)\[\];/);
  assert.match(out, /export type Both = string & \("x" \| "y"\);/);
  assert.match(out, /export type NoProps = \{ \[key: string\]: JsonValue \};/);
  assert.match(out, /export interface Closed \{\n {2}a: string;\n\}/);
  assert.match(out, /export type T = string \| number;/);
  assert.match(out, /export type Bare = string \| number;/);
});

test('CLI writes the expected file', () => {
  withScratch((dir) => {
    const out = join(dir, 'nested.d.ts');
    const r = cli('--schemas', schemaDir, '--out', out);
    assert.equal(r.status, 0, r.stderr);
    assert.equal(readFileSync(out, 'utf8'), readFileSync(expectedPath, 'utf8'));
    unlinkSync(out);
  });
});

test('--check: 0 when equal, 1 (and writes nothing) when different or missing', () => {
  withScratch((dir) => {
    const out = join(dir, 'types.d.ts');
    assert.equal(cli('--schemas', schemaDir, '--out', out, '--check').status, 1, 'missing file differs');
    assert.equal(existsSync(out), false, '--check must not create the file');

    copyFileSync(expectedPath, out);
    const same = cli('--schemas', schemaDir, '--out', out, '--check');
    assert.equal(same.status, 0, same.stderr);

    const changed = readFileSync(out, 'utf8').replace('export type Level = 0 | 1 | 2;', 'export type Level = 0 | 1;');
    writeFileSync(out, changed);
    const diff = cli('--schemas', schemaDir, '--out', out, '--check');
    assert.equal(diff.status, 1);
    assert.match(diff.stderr, /types\.d\.ts/);
    assert.match(diff.stderr, /first difference at line \d+/);
    assert.equal(readFileSync(out, 'utf8'), changed, '--check must not rewrite the file');
    unlinkSync(out);
  });
});

const errorCases = {
  'unknown keyword': {
    files: { 'a.schema.json': schema('urn:t:a:1', { $defs: { x: { type: 'string', format: 'uri' } } }) },
    expect: [/a\.schema\.json/, /\/\$defs\/x\/format/, /unknown keyword "format"/],
  },
  'unknown keyword inside not': {
    files: { 'a.schema.json': schema('urn:t:a:1', { $defs: { x: { not: { contains: {} } } } }) },
    expect: [/\/\$defs\/x\/not\/contains/],
  },
  'unresolvable $ref (missing def)': {
    files: { 'a.schema.json': schema('urn:t:a:1', { $defs: { x: { properties: { p: { $ref: '#/$defs/nope' } } } } }) },
    expect: [/a\.schema\.json/, /\/\$defs\/x\/properties\/p\/\$ref/, /unresolvable/],
  },
  'unresolvable $ref (unknown id)': {
    files: { 'a.schema.json': schema('urn:t:a:1', { $defs: { x: { $ref: 'urn:t:zzz:1#/$defs/y' } } }) },
    expect: [/\/\$defs\/x\/\$ref/, /urn:t:zzz:1/],
  },
  'unresolvable $ref (root without a title)': {
    files: {
      'a.schema.json': schema('urn:t:a:1', { $defs: { x: { $ref: 'urn:t:b:1' } } }),
      'b.schema.json': schema('urn:t:b:1', { $defs: { y: { type: 'string' } } }),
    },
    expect: [/\/\$defs\/x\/\$ref/, /no title/],
  },
  'unsupported $ref form': {
    files: { 'a.schema.json': schema('urn:t:a:1', { $defs: { x: { $ref: '#/properties/p' }, y: { type: 'string' } } }) },
    expect: [/\/\$defs\/x\/\$ref/, /unsupported \$ref/],
  },
  'name clash within a file': {
    files: { 'a.schema.json': schema('urn:t:a:1', { $defs: { numberExpr: { type: 'number' }, 'number-expr': { type: 'string' } } }) },
    expect: [/a\.schema\.json/, /\/\$defs\/number-expr/, /name clash/, /NumberExpr/],
  },
  'name clash across files': {
    files: {
      'a.schema.json': schema('urn:t:a:1', { $defs: { thing: { type: 'string' } } }),
      'b.schema.json': schema('urn:t:b:1', { $defs: { Thing: { type: 'number' } } }),
    },
    expect: [/b\.schema\.json/, /\/\$defs\/Thing/, /name clash/],
  },
  'name clash between a root title and a def': {
    files: { 'a.schema.json': schema('urn:t:a:1', { title: 'Scene', type: 'object', $defs: { scene: { type: 'string' } } }) },
    expect: [/\/\$defs\/scene/, /name clash/],
  },
  'name clash with JsonValue': {
    files: { 'a.schema.json': schema('urn:t:a:1', { $defs: { jsonValue: { type: 'string' } } }) },
    expect: [/name clash/, /JsonValue/],
  },
  'additionalProperties schema together with properties': {
    files: { 'a.schema.json': schema('urn:t:a:1', { $defs: { x: { type: 'object', properties: { a: { type: 'string' } }, additionalProperties: { type: 'string' } } } }) },
    expect: [/\/\$defs\/x\/additionalProperties/, /together with properties/],
  },
  'root without $id': {
    files: { 'a.schema.json': { $defs: {} } },
    expect: [/a\.schema\.json/, /\/\$id/],
  },
  'invalid JSON': {
    raw: { 'a.schema.json': '{ nope' },
    expect: [/a\.schema\.json/, /invalid JSON/],
  },
};

for (const [name, c] of Object.entries(errorCases)) {
  test(`error exits 2 with file and pointer: ${name}`, () => {
    const r = withScratch((dir) => {
      const sdir = join(dir, 's');
      mkdirSync(sdir);
      const names = Object.keys(c.files ?? c.raw);
      for (const n of names) writeFileSync(join(sdir, n), c.raw ? c.raw[n] : JSON.stringify(c.files[n]));
      const out = join(dir, 'out.d.ts');
      const res = cli('--schemas', sdir, '--out', out);
      const wrote = existsSync(out);
      for (const n of names) unlinkSync(join(sdir, n));
      rmdirSync(sdir);
      return { ...res, wrote };
    });
    assert.equal(r.status, 2, r.stderr);
    assert.equal(r.wrote, false, 'nothing is written on error');
    for (const re of c.expect) assert.match(r.stderr, re);
  });
}

test('bad arguments exit 2', () => {
  assert.equal(cli().status, 2);
  assert.equal(cli('--schemas', schemaDir).status, 2);
  assert.equal(cli('--schemas', join(fixtures, 'nope'), '--out', join(root, 'x.d.ts')).status, 2);
  assert.equal(existsSync(join(root, 'x.d.ts')), false);
});

test('--check also exits 2 on a schema error', () => {
  const r = runCli({ 'a.schema.json': schema('urn:t:a:1', { $defs: { x: { bogus: 1 } } }) }, ['--check']);
  assert.equal(r.status, 2);
});

test('generated types compile, and wrong values are rejected (tsc)', { skip: TSC && existsSync(TSC) ? false : 'set TSC to a TypeScript compiler to run' }, () => {
  withScratch((dir) => {
    writeFileSync(join(dir, 'generated.d.ts'), generate(loadFixtures()));
    copyFileSync(join(fixtures, 'usage.ts'), join(dir, 'usage.ts'));
    const r = spawnSync(
      process.execPath,
      [TSC, '--noEmit', '--strict', '--target', 'ES2022', '--lib', 'ES2022', '--moduleResolution', 'bundler', '--module', 'ESNext', 'generated.d.ts', 'usage.ts'],
      { cwd: dir, encoding: 'utf8' },
    );
    assert.equal(r.status, 0, `${r.stdout}${r.stderr}`);
  });
});
