#!/usr/bin/env node
// Turns a set of JSON Schema (draft 2020-12, strict subset) files into one TypeScript declaration file, and an OpenAPI
// 3.1.1 request index over them (strict subset) into its ApiOperations. Dependency-free: Node >= 22, built-ins only.
//
//   node tools/gen-types.mjs --schemas <dir> --out <file.d.ts> [--openapi <openapi.json>] [--check]
//
// Without --openapi, the openapi.json next to the schemas folder is read when there is one.
//
// Exit codes: 0 ok, 1 --check found a difference, 2 bad arguments or a schema that can't be translated.

import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync, statSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const HEADER =
  '// Generated by tools/gen-types.mjs from schemas/*.schema.json. Do not edit; run `npm run gen`.';
const JSON_VALUE =
  'export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };';

const KEYWORDS = new Set([
  '$schema', '$id', '$defs', '$ref', '$comment', 'title', 'description', 'default', 'examples',
  'deprecated', 'readOnly', 'writeOnly', 'allOf', 'anyOf', 'oneOf', 'not', 'properties',
  'additionalProperties', 'propertyNames', 'items', 'prefixItems', 'type', 'enum', 'const',
  'minimum', 'maximum', 'exclusiveMinimum', 'exclusiveMaximum', 'minLength', 'maxLength',
  'pattern', 'minItems', 'maxItems', 'uniqueItems', 'required', 'minProperties', 'maxProperties',
]);

// Keywords that carry no type information; a root made only of these is a `$defs` container.
const ANNOTATIONS = new Set([
  '$schema', '$id', '$defs', '$comment', 'title', 'description', 'default', 'examples',
  'deprecated', 'readOnly', 'writeOnly',
]);

/** A schema the generator can't translate. `message` is already formatted as `file#/pointer: text`. */
export class GenError extends Error {
  constructor(file, pointer, text) {
    super(`${file}#${pointer}: ${text}`);
    this.name = 'GenError';
    this.file = file;
    this.pointer = pointer;
  }
}

const isObj = (v) => typeof v === 'object' && v !== null && !Array.isArray(v);
const has = (o, k) => Object.prototype.hasOwnProperty.call(o, k);
const ptr = (base, ...segs) =>
  base + segs.map((s) => '/' + String(s).replace(/~/g, '~0').replace(/\//g, '~1')).join('');

/** `numberExpr` -> `NumberExpr`, `commit-request` -> `CommitRequest`. Returns '' when nothing usable is left. */
export function pascalCase(s) {
  return String(s)
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join('');
}

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const propKey = (k) => (IDENT.test(k) ? k : JSON.stringify(k));

// ---------------------------------------------------------------------------------------------
// Registry: ids, names, $ref resolution
// ---------------------------------------------------------------------------------------------

function buildRegistry(schemas) {
  const byId = new Map(); // $id -> { file, json, defs: Map<defName, TypeName>, rootName }
  // TypeName -> location. ApiOperations is the request index's (openapi.json).
  const names = new Map([['JsonValue', 'the generated header'], ['ApiOperations', 'the generated request index']]);
  const entries = [];

  for (const { file, json } of schemas) {
    if (!isObj(json)) throw new GenError(file, '', 'schema root must be an object');
    if (typeof json.$id !== 'string' || !/^[A-Za-z][A-Za-z0-9+.-]*:/.test(json.$id)) {
      throw new GenError(file, '/$id', 'root needs an absolute $id (for example "urn:app:name:1")');
    }
    if (byId.has(json.$id)) {
      throw new GenError(file, '/$id', `duplicate $id ${json.$id} (also in ${byId.get(json.$id).file})`);
    }
    const entry = { file, json, defs: new Map(), rootName: null, isRootType: false };
    byId.set(json.$id, entry);
    entries.push(entry);
  }

  const claim = (entry, pointer, name, what) => {
    if (!name || /^[0-9]/.test(name)) {
      throw new GenError(entry.file, pointer, `${what} "${name}" does not give a usable type name`);
    }
    if (names.has(name)) {
      throw new GenError(entry.file, pointer, `name clash: ${what} becomes ${name}, already used by ${names.get(name)}`);
    }
    names.set(name, `${entry.file}#${pointer}`);
    return name;
  };

  for (const entry of entries) {
    const { json } = entry;
    if (typeof json.title === 'string' && Object.keys(json).some((k) => !ANNOTATIONS.has(k))) {
      entry.rootName = claim(entry, '/title', pascalCase(json.title), `title "${json.title}"`);
      entry.isRootType = true;
    }
    if (has(json, '$defs')) {
      if (!isObj(json.$defs)) throw new GenError(entry.file, '/$defs', '$defs must be an object');
      for (const key of Object.keys(json.$defs)) {
        entry.defs.set(key, claim(entry, ptr('/$defs', key), pascalCase(key), `def "${key}"`));
      }
    }
  }
  return byId;
}

/** Resolves a `$ref` seen in `entry` at `pointer` to a type name. */
function resolveRef(ref, entry, byId, pointer) {
  if (typeof ref !== 'string') throw new GenError(entry.file, pointer, '$ref must be a string');
  const hash = ref.indexOf('#');
  const base = hash < 0 ? ref : ref.slice(0, hash);
  const frag = hash < 0 ? '' : ref.slice(hash + 1);
  let target = entry;
  if (base !== '') {
    target = byId.get(base);
    if (!target) throw new GenError(entry.file, pointer, `unresolvable $ref "${ref}": no schema has $id "${base}"`);
  }
  if (frag === '') {
    if (!target.isRootType) {
      throw new GenError(entry.file, pointer, `unresolvable $ref "${ref}": the root of ${target.file} has no title, so it has no type name`);
    }
    return target.rootName;
  }
  const m = /^\/\$defs\/([^/]+)$/.exec(frag);
  if (!m) throw new GenError(entry.file, pointer, `unsupported $ref "${ref}": only #/$defs/<name>, <id>#/$defs/<name> and <id> are allowed`);
  const key = m[1].replace(/~1/g, '/').replace(/~0/g, '~');
  const name = target.defs.get(key);
  if (!name) throw new GenError(entry.file, pointer, `unresolvable $ref "${ref}": ${target.file} has no $defs/${key}`);
  return name;
}

// ---------------------------------------------------------------------------------------------
// Validation pass: unknown keywords, malformed values, unresolvable refs (everywhere, `not` included)
// ---------------------------------------------------------------------------------------------

function validate(s, entry, byId, p) {
  if (typeof s === 'boolean') return;
  const fail = (at, text) => {
    throw new GenError(entry.file, at, text);
  };
  if (!isObj(s)) fail(p, 'a schema must be an object or a boolean');
  for (const k of Object.keys(s)) {
    if (!KEYWORDS.has(k)) fail(ptr(p, k), `unknown keyword "${k}"`);
  }
  if (has(s, '$ref')) resolveRef(s.$ref, entry, byId, ptr(p, '$ref'));
  for (const k of ['allOf', 'anyOf', 'oneOf', 'prefixItems']) {
    if (!has(s, k)) continue;
    if (!Array.isArray(s[k])) fail(ptr(p, k), `${k} must be an array`);
    s[k].forEach((sub, i) => validate(sub, entry, byId, ptr(p, k, i)));
  }
  for (const k of ['not', 'additionalProperties', 'propertyNames', 'items']) {
    if (has(s, k)) validate(s[k], entry, byId, ptr(p, k));
  }
  for (const k of ['properties', '$defs']) {
    if (!has(s, k)) continue;
    if (!isObj(s[k])) fail(ptr(p, k), `${k} must be an object`);
    for (const key of Object.keys(s[k])) validate(s[k][key], entry, byId, ptr(p, k, key));
  }
  if (has(s, 'required') && !(Array.isArray(s.required) && s.required.every((r) => typeof r === 'string'))) {
    fail(ptr(p, 'required'), 'required must be an array of strings');
  }
  if (has(s, 'enum') && !Array.isArray(s.enum)) fail(ptr(p, 'enum'), 'enum must be an array');
  if (has(s, 'type')) {
    const t = s.type;
    if (!(typeof t === 'string' || (Array.isArray(t) && t.every((x) => typeof x === 'string')))) {
      fail(ptr(p, 'type'), 'type must be a string or an array of strings');
    }
  }
  for (const k of ['minimum', 'maximum', 'exclusiveMinimum', 'exclusiveMaximum', 'minLength', 'maxLength', 'minItems', 'maxItems']) {
    if (has(s, k) && typeof s[k] !== 'number') fail(ptr(p, k), `${k} must be a number`);
  }
  if (has(s, 'pattern') && typeof s.pattern !== 'string') fail(ptr(p, 'pattern'), 'pattern must be a string');
}

// ---------------------------------------------------------------------------------------------
// JSDoc
// ---------------------------------------------------------------------------------------------

const esc = (t) => t.replace(/\*\//g, '*\\/');
const textLines = (t) => String(t).split(/\r\n|\r|\n/).map((l) => l.trimEnd());

function bounds(label, lo, hi, loEx, hiEx) {
  const parts = [];
  if (lo !== undefined && hi !== undefined && loEx === undefined && hiEx === undefined) {
    return `${label}: ${lo}–${hi}.`;
  }
  if (lo !== undefined) parts.push(`≥ ${lo}`);
  if (loEx !== undefined) parts.push(`> ${loEx}`);
  if (hi !== undefined) parts.push(`≤ ${hi}`);
  if (hiEx !== undefined) parts.push(`< ${hiEx}`);
  return parts.length ? `${label}: ${parts.join(', ')}.` : null;
}

function docLines(s) {
  if (!isObj(s)) return [];
  const out = [];
  if (typeof s.title === 'string' && s.title.trim() !== '') out.push(...textLines(s.title));
  if (typeof s.description === 'string' && s.description.trim() !== '') {
    if (out.length) out.push('');
    out.push(...textLines(s.description));
  }
  if (s.readOnly === true) out.push('Set by the engine; ignored when a client sends it.');
  const num = (k) => (typeof s[k] === 'number' ? s[k] : undefined);
  for (const line of [
    bounds('Range', num('minimum'), num('maximum'), num('exclusiveMinimum'), num('exclusiveMaximum')),
    bounds('Length', num('minLength'), num('maxLength')),
    bounds('Items', num('minItems'), num('maxItems')),
  ]) {
    if (line) out.push(line);
  }
  if (s.uniqueItems === true) out.push('Unique items.');
  if (typeof s.pattern === 'string') out.push(`Pattern: \`${s.pattern}\`.`);
  // Tags last, so the prose above is not swallowed by them.
  if (has(s, 'default')) out.push(`@default ${JSON.stringify(s.default)}`);
  if (s.deprecated === true) out.push('@deprecated');
  return out;
}

/** A `/** ... *\/` block for `s`, indented for `level`, ending in a newline; '' when there is nothing to say. */
function docBlock(s, level) {
  const lines = docLines(s).map(esc);
  if (lines.length === 0) return '';
  const pad = '  '.repeat(level);
  if (lines.length === 1) return `${pad}/** ${lines[0]} */\n`;
  return `${pad}/**\n${lines.map((l) => (l === '' ? `${pad} *` : `${pad} * ${l}`)).join('\n')}\n${pad} */\n`;
}

// ---------------------------------------------------------------------------------------------
// Type translation. A translated type is { s: source text, k: 'atom' | 'union' | 'inter' }.
// ---------------------------------------------------------------------------------------------

const atom = (s) => ({ s, k: 'atom' });

function union(list) {
  const seen = new Set();
  const uniq = list.filter((t) => (seen.has(t.s) ? false : (seen.add(t.s), true)));
  if (uniq.length === 0) return atom('never');
  if (uniq.length === 1) return uniq[0];
  return { s: uniq.map((t) => t.s).join(' | '), k: 'union' };
}

function intersection(list) {
  if (list.length === 1) return list[0];
  return { s: list.map((t) => (t.k === 'union' ? `(${t.s})` : t.s)).join(' & '), k: 'inter' };
}

const wrap = (t) => (t.k === 'atom' ? t.s : `(${t.s})`);

function literal(v, ctx, p) {
  if (v === null || ['string', 'number', 'boolean'].includes(typeof v)) return atom(JSON.stringify(v));
  throw new GenError(ctx.entry.file, p, 'only string, number, boolean and null values are supported in const and enum');
}

function objectLiteral(s, level, ctx, p) {
  const ap = s.additionalProperties;
  if (has(s, 'properties')) {
    if (isObj(ap)) {
      throw new GenError(ctx.entry.file, ptr(p, 'additionalProperties'), 'additionalProperties as a schema together with properties is not supported');
    }
    const required = new Set(Array.isArray(s.required) ? s.required : []);
    const pad = '  '.repeat(level + 1);
    const lines = Object.keys(s.properties).map((key) => {
      const sub = s.properties[key];
      const t = conv(sub, level + 1, ctx, ptr(p, 'properties', key));
      return `${docBlock(sub, level + 1)}${pad}${propKey(key)}${required.has(key) ? '' : '?'}: ${t.s};`;
    });
    if (lines.length === 0) return atom('{}');
    return atom(`{\n${lines.join('\n')}\n${'  '.repeat(level)}}`);
  }
  if (ap === undefined || ap === true) return atom('{ [key: string]: JsonValue }');
  if (ap === false) return atom('{ [key: string]: never }');
  return atom(`{ [key: string]: ${conv(ap, level, ctx, ptr(p, 'additionalProperties')).s} }`);
}

function arrayType(s, level, ctx, p) {
  if (Array.isArray(s.prefixItems)) {
    const min = Number.isInteger(s.minItems) ? s.minItems : 0;
    const els = s.prefixItems.map((sub, i) => {
      const t = conv(sub, level, ctx, ptr(p, 'prefixItems', i));
      return (i >= min ? `${wrap(t)}?` : t.s);
    });
    if (has(s, 'items') && s.items !== false) {
      els.push(`...${wrap(conv(s.items, level, ctx, ptr(p, 'items')))}[]`);
    }
    return atom(`[${els.join(', ')}]`);
  }
  if (!has(s, 'items')) return atom('JsonValue[]');
  if (s.items === false) return atom('never[]');
  return atom(`${wrap(conv(s.items, level, ctx, ptr(p, 'items')))}[]`);
}

function conv(s, level, ctx, p) {
  if (s === true) return atom('JsonValue');
  if (s === false) return atom('never');

  const parts = [];
  const hasLiteral = has(s, 'const') || has(s, 'enum');
  const hasOther = has(s, '$ref') || hasLiteral || has(s, 'anyOf') || has(s, 'oneOf') || has(s, 'allOf');

  if (has(s, '$ref')) parts.push(atom(resolveRef(s.$ref, ctx.entry, ctx.byId, ptr(p, '$ref'))));

  // `type` is implied by const/enum, so it is not repeated there.
  if (!hasLiteral) {
    let types;
    if (has(s, 'type')) types = Array.isArray(s.type) ? s.type : [s.type];
    else if (has(s, 'properties') || has(s, 'additionalProperties')) types = ['object'];
    else if (has(s, 'items') || has(s, 'prefixItems')) types = ['array'];
    else types = [];
    // A bare `type: object` beside a union/ref/allOf says nothing the other parts don't.
    const bareObject =
      types.length === 1 && types[0] === 'object' && !has(s, 'properties') && !has(s, 'additionalProperties');
    if (!(bareObject && hasOther)) {
      const ts = types.map((t) => {
        switch (t) {
          case 'string': return atom('string');
          case 'number':
          case 'integer': return atom('number');
          case 'boolean': return atom('boolean');
          case 'null': return atom('null');
          case 'object': return objectLiteral(s, level, ctx, p);
          case 'array': return arrayType(s, level, ctx, p);
          default: throw new GenError(ctx.entry.file, ptr(p, 'type'), `unsupported type "${t}"`);
        }
      });
      if (ts.length) parts.push(union(ts));
    }
  }

  if (has(s, 'const')) parts.push(literal(s.const, ctx, ptr(p, 'const')));
  if (has(s, 'enum')) parts.push(union(s.enum.map((v, i) => literal(v, ctx, ptr(p, 'enum', i)))));
  for (const k of ['anyOf', 'oneOf']) {
    if (has(s, k)) parts.push(union(s[k].map((sub, i) => conv(sub, level, ctx, ptr(p, k, i)))));
  }
  if (has(s, 'allOf')) {
    for (const [i, sub] of s.allOf.entries()) parts.push(conv(sub, level, ctx, ptr(p, 'allOf', i)));
  }
  // `not` is ignored.

  if (parts.length === 0) return atom('JsonValue');
  return intersection(parts);
}

function isInterfaceShape(s) {
  if (!isObj(s) || !isObj(s.properties)) return false;
  if (['oneOf', 'anyOf', 'allOf', '$ref', 'enum', 'const'].some((k) => has(s, k))) return false;
  return !has(s, 'type') || s.type === 'object';
}

function declaration(name, s, ctx, p) {
  const doc = docBlock(s, 0);
  if (isInterfaceShape(s)) return `${doc}export interface ${name} ${objectLiteral(s, 0, ctx, p).s}`;
  return `${doc}export type ${name} = ${conv(s, 0, ctx, p).s};`;
}

// ---------------------------------------------------------------------------------------------
// The request index: an OpenAPI 3.1.1 document (openapi.json) in a strict subset, read and checked like the schemas,
// and turned into ApiOperations
// ---------------------------------------------------------------------------------------------

/** The HTTP methods of a path item, in the order ApiOperations lists them. */
export const METHODS = ['get', 'head', 'post', 'put', 'patch', 'delete', 'options', 'trace'];

/** The fields the subset allows in each OpenAPI object (OAS 3.1.1's field tables, less what the engine API doesn't use). */
const FIELDS = {
  document: ['openapi', 'info', 'jsonSchemaDialect', 'servers', 'paths', 'components'],
  info: ['title', 'summary', 'description', 'version', 'license'],
  license: ['name', 'identifier', 'url'],
  server: ['url', 'description', 'variables'],
  serverVariable: ['enum', 'default', 'description'],
  pathItem: ['summary', 'description', 'parameters', ...METHODS],
  operation: ['operationId', 'summary', 'description', 'parameters', 'requestBody', 'responses', 'security', 'deprecated', 'x-infopanel-socket'],
  parameter: ['name', 'in', 'description', 'required', 'deprecated', 'schema'],
  requestBody: ['description', 'content', 'required'],
  mediaType: ['schema'],
  response: ['description', 'headers', 'content'],
  header: ['description', 'required', 'deprecated', 'schema'],
  components: ['parameters', 'responses', 'securitySchemes'],
  securityScheme: ['type', 'description', 'name', 'in', 'scheme', 'bearerFormat'],
  reference: ['$ref', 'summary', 'description'],
  socket: ['subprotocol', 'clientMessage', 'serverMessage', 'frameHeader'],
};

const JSON_MEDIA = /^application\/([A-Za-z0-9.+-]+\+)?json$/;

/** Whether a media type carries JSON (application/json, application/problem+json). */
export const isJsonMedia = (media) => JSON_MEDIA.test(media);

/** The types and keywords of a scalar a body array may hold inline (the font list's strings): no object or array keywords. */
const SCALAR_TYPES = new Set(['string', 'number', 'integer', 'boolean', 'null']);
const SCALAR_KEYWORDS = new Set([
  '$comment', 'title', 'description', 'default', 'examples', 'deprecated', 'readOnly', 'writeOnly', 'type', 'enum', 'const', 'minimum', 'maximum', 'exclusiveMinimum', 'exclusiveMaximum', 'minLength',
  'maxLength', 'pattern',
]);

/**
 * Checks an OpenAPI document against the subset and returns its operations, in document order:
 * `{ key: 'GET /path', method, path, operationId, summary, description, security, params, query, request, responses,
 * socket, pointer }`, with references resolved. `params` and `query` are `{ name, required, description, schema,
 * pointer }`; `request` is null or `{ required, description, content }`; each response is `{ status, description,
 * content, headers, pointer }`; `content` is `[{ media, schema, pointer }]` (schema null when absent). Every Schema
 * Object is checked like a schema (keywords, `$ref`s by id) against the registry of `schemas`.
 */
export function readOperations(openapi, schemas) {
  const sorted = [...schemas].sort((a, b) => (a.file < b.file ? -1 : a.file > b.file ? 1 : 0));
  const byId = buildRegistry(sorted);
  return checkOpenApi(openapi, byId).operations;
}

function checkOpenApi({ file, json: doc }, byId) {
  const entry = { file, json: doc, defs: new Map(), rootName: null, isRootType: false };
  const fail = (p, text) => {
    throw new GenError(file, p, text);
  };
  const object = (v, p, what) => {
    if (!isObj(v)) fail(p, `${what} must be an object`);
    return v;
  };
  const fields = (v, kind, p) => {
    object(v, p, kind);
    for (const k of Object.keys(v)) {
      if (!FIELDS[kind].includes(k)) fail(ptr(p, k), `unknown key "${k}" in ${kind === 'document' ? 'the document' : `a ${kind} object`}`);
    }
    return v;
  };
  const text = (v, p, what, optional = true) => {
    if (v === undefined && optional) return;
    if (typeof v !== 'string') fail(p, `${what} must be a string`);
  };
  const schema = (s, p) => {
    validate(s, entry, byId, p);
    return s;
  };
  // Every component an operation refers to, as `<kind>/<name>`: one no operation refers to is refused below.
  const used = new Set();
  // A Reference Object to `#/components/<kind>/<name>`, or the object itself.
  const deref = (v, kind, p) => {
    if (!isObj(v) || !has(v, '$ref')) return { value: v, pointer: p };
    fields(v, 'reference', p);
    const m = typeof v.$ref === 'string' ? /^#\/components\/([^/]+)\/([^/]+)$/.exec(v.$ref) : null;
    if (!m || m[1] !== kind) fail(ptr(p, '$ref'), `unsupported $ref "${v.$ref}": only #/components/${kind}/<name> is allowed here`);
    const target = doc.components?.[kind]?.[m[2]];
    if (target === undefined) fail(ptr(p, '$ref'), `unresolvable $ref "${v.$ref}"`);
    used.add(`${kind}/${m[2]}`);
    return { value: target, pointer: ptr('/components', kind, m[2]) };
  };

  fields(doc, 'document', '');
  if (doc.openapi !== '3.1.1') fail('/openapi', 'openapi must be "3.1.1"');
  fields(doc.info, 'info', '/info');
  text(doc.info.title, '/info/title', 'info.title', false);
  text(doc.info.version, '/info/version', 'info.version', false);
  for (const k of ['summary', 'description']) text(doc.info[k], ptr('/info', k), `info.${k}`);
  if (has(doc.info, 'license')) fields(doc.info.license, 'license', '/info/license');
  if (has(doc, 'jsonSchemaDialect') && doc.jsonSchemaDialect !== 'https://json-schema.org/draft/2020-12/schema') {
    fail('/jsonSchemaDialect', 'jsonSchemaDialect must be draft 2020-12, the schemas\' dialect');
  }
  if (has(doc, 'servers')) {
    if (!Array.isArray(doc.servers)) fail('/servers', 'servers must be an array');
    doc.servers.forEach((server, i) => {
      const p = ptr('/servers', i);
      fields(server, 'server', p);
      text(server.url, ptr(p, 'url'), 'a server\'s url', false);
      for (const [name, variable] of Object.entries(object(server.variables ?? {}, ptr(p, 'variables'), 'variables'))) {
        fields(variable, 'serverVariable', ptr(p, 'variables', name));
        text(variable.default, ptr(p, 'variables', name, 'default'), 'a server variable\'s default', false);
      }
    });
  }

  const components = doc.components === undefined ? {} : fields(doc.components, 'components', '/components');
  const schemes = object(components.securitySchemes ?? {}, '/components/securitySchemes', 'securitySchemes');
  for (const [name, scheme] of Object.entries(schemes)) {
    const p = ptr('/components/securitySchemes', name);
    fields(scheme, 'securityScheme', p);
    if (!['http', 'apiKey'].includes(scheme.type)) fail(ptr(p, 'type'), 'a security scheme\'s type must be "http" or "apiKey"');
  }
  for (const kind of ['parameters', 'responses']) object(components[kind] ?? {}, ptr('/components', kind), kind);

  const parameter = (raw, p) => {
    const { value: v, pointer } = deref(raw, 'parameters', p);
    fields(v, 'parameter', pointer);
    text(v.name, ptr(pointer, 'name'), 'a parameter\'s name', false);
    if (!['path', 'query'].includes(v.in)) fail(ptr(pointer, 'in'), 'a parameter is "in" "path" or "query"');
    if (v.in === 'path' && v.required !== true) fail(ptr(pointer, 'required'), 'a path parameter must be required');
    if (has(v, 'required') && typeof v.required !== 'boolean') fail(ptr(pointer, 'required'), 'required must be a boolean');
    text(v.description, ptr(pointer, 'description'), 'a description');
    if (!has(v, 'schema')) fail(pointer, 'a parameter needs a schema');
    return { name: v.name, in: v.in, required: v.required === true, description: v.description, schema: schema(v.schema, ptr(pointer, 'schema')), pointer };
  };
  // A body names its definitions; it never defines one: a bare `{"$ref"}` to a definition (or a schema's root).
  const isBareRef = (s) => isObj(s) && Object.keys(s).length === 1 && has(s, '$ref');
  const bareRef = (s, p, what) => {
    if (!isBareRef(s)) fail(p, `${what} must be a bare {"$ref"} to a definition, with no other keys`);
  };
  // What a JSON body's schema may be: a definition, a oneOf of definitions, or an array of a definition or of a scalar.
  const bodySchema = (s, p) => {
    if (isBareRef(s)) return;
    const keys = isObj(s) ? Object.keys(s).sort().join(',') : '';
    if (keys === 'oneOf') {
      if (s.oneOf.length === 0) fail(ptr(p, 'oneOf'), 'a body\'s oneOf names at least one definition');
      s.oneOf.forEach((b, i) => bareRef(b, ptr(p, 'oneOf', i), 'each branch of a body\'s oneOf'));
      return;
    }
    if (keys === 'items,type' && s.type === 'array') {
      const items = s.items;
      if (isBareRef(items)) return;
      if (isObj(items) && SCALAR_TYPES.has(items.type) && Object.keys(items).every((k) => SCALAR_KEYWORDS.has(k))) return;
      fail(ptr(p, 'items'), 'a body array\'s items must be a bare {"$ref"} to a definition, or a scalar type with no object or array keywords');
    }
    fail(p, 'a JSON body\'s schema must be {"$ref"}, {"oneOf": [{"$ref"}, …]} or {"type": "array", "items": …}: define its shape in the schemas, not here');
  };
  const content = (v, p) => {
    object(v, p, 'content');
    if (Object.keys(v).length === 0) fail(p, 'content must name at least one media type');
    return Object.entries(v).map(([media, m]) => {
      const mp = ptr(p, media);
      if (!/^[a-z*]+\/[A-Za-z0-9.+*-]+$/.test(media)) fail(mp, `"${media}" is not a media type`);
      fields(m, 'mediaType', mp);
      if (isJsonMedia(media)) {
        if (!has(m, 'schema')) fail(mp, `a JSON body (${media}) needs a schema`);
        schema(m.schema, ptr(mp, 'schema'));
        bodySchema(m.schema, ptr(mp, 'schema'));
      } else if (has(m, 'schema')) {
        fail(ptr(mp, 'schema'), `a body that isn't JSON (${media}) has no schema: its media type names it`);
      }
      return { media, schema: has(m, 'schema') ? m.schema : null, pointer: mp };
    });
  };
  const headers = (v, p) =>
    Object.entries(object(v ?? {}, p, 'headers')).map(([name, h]) => {
      const hp = ptr(p, name);
      fields(h, 'header', hp);
      if (!has(h, 'schema')) fail(hp, 'a header needs a schema');
      schema(h.schema, ptr(hp, 'schema'));
      return { name, required: h.required === true, description: h.description };
    });

  const operations = [];
  const ids = new Map();
  for (const [path, item] of Object.entries(object(doc.paths, '/paths', 'paths'))) {
    const pp = ptr('/paths', path);
    if (!/^\/[^?#]*$/.test(path)) fail(pp, `path "${path}" must start with "/"`);
    fields(item, 'pathItem', pp);
    const shared = (item.parameters ?? []).map((v, i) => parameter(v, ptr(pp, 'parameters', i)));
    if (has(item, 'parameters') && !Array.isArray(item.parameters)) fail(ptr(pp, 'parameters'), 'parameters must be an array');
    const templated = [...path.matchAll(/\{([^}]*)\}/g)].map((m) => m[1]);
    for (const method of METHODS.filter((m) => has(item, m))) {
      const op = item[method];
      const p = ptr(pp, method);
      fields(op, 'operation', p);
      if (typeof op.operationId !== 'string' || !/^[A-Za-z][A-Za-z0-9]*$/.test(op.operationId)) {
        fail(ptr(p, 'operationId'), 'every operation needs an operationId of letters and digits');
      }
      if (ids.has(op.operationId)) fail(ptr(p, 'operationId'), `duplicate operationId "${op.operationId}" (also at ${ids.get(op.operationId)})`);
      ids.set(op.operationId, `#${p}`);
      text(op.summary, ptr(p, 'summary'), 'a summary');
      text(op.description, ptr(p, 'description'), 'a description');
      if (has(op, 'parameters') && !Array.isArray(op.parameters)) fail(ptr(p, 'parameters'), 'parameters must be an array');
      const own = (op.parameters ?? []).map((v, i) => parameter(v, ptr(p, 'parameters', i)));
      const all = new Map();
      for (const prm of [...shared, ...own]) all.set(`${prm.in} ${prm.name}`, prm);
      const pathParams = [...all.values()].filter((prm) => prm.in === 'path');
      for (const name of templated) {
        if (!all.has(`path ${name}`)) fail(p, `path parameter {${name}} of "${path}" isn't declared`);
      }
      for (const prm of pathParams) {
        if (!templated.includes(prm.name)) fail(prm.pointer, `path parameter "${prm.name}" isn't in "${path}"`);
      }

      if (!Array.isArray(op.security)) fail(ptr(p, 'security'), 'every operation states its security: [] for none');
      op.security.forEach((req, i) => {
        const rp = ptr(p, 'security', i);
        for (const [name, roles] of Object.entries(object(req, rp, 'a security requirement'))) {
          if (!has(schemes, name)) fail(ptr(rp, name), `no security scheme "${name}" in components.securitySchemes`);
          if (!Array.isArray(roles) || !roles.every((r) => typeof r === 'string')) fail(ptr(rp, name), 'a security requirement lists strings');
        }
      });

      let request = null;
      if (has(op, 'requestBody')) {
        const rb = fields(op.requestBody, 'requestBody', ptr(p, 'requestBody'));
        request = { required: rb.required === true, description: rb.description, content: content(rb.content, ptr(p, 'requestBody', 'content')) };
      }

      const responses = Object.entries(object(op.responses, ptr(p, 'responses'), 'responses')).map(([status, raw]) => {
        const sp = ptr(p, 'responses', status);
        if (!/^[1-5][0-9][0-9]$/.test(status)) fail(sp, `response "${status}" must be a status code from 100 to 599`);
        const { value: r, pointer } = deref(raw, 'responses', sp);
        fields(r, 'response', pointer);
        text(r.description, ptr(pointer, 'description'), 'a response\'s description', false);
        return {
          status: Number(status),
          description: r.description,
          content: has(r, 'content') ? content(r.content, ptr(pointer, 'content')) : [],
          headers: headers(r.headers, ptr(pointer, 'headers')),
          pointer: sp,
        };
      });
      if (responses.length === 0) fail(ptr(p, 'responses'), 'an operation answers at least one status');

      let socket = null;
      if (has(op, 'x-infopanel-socket')) {
        const xp = ptr(p, 'x-infopanel-socket');
        const x = fields(op['x-infopanel-socket'], 'socket', xp);
        text(x.subprotocol, ptr(xp, 'subprotocol'), 'subprotocol', false);
        for (const k of ['clientMessage', 'serverMessage', 'frameHeader']) {
          if (!has(x, k)) fail(xp, `x-infopanel-socket needs ${k}`);
          schema(x[k], ptr(xp, k));
          bareRef(x[k], ptr(xp, k), `x-infopanel-socket's ${k}`);
        }
        socket = { subprotocol: x.subprotocol, clientMessage: x.clientMessage, serverMessage: x.serverMessage, frameHeader: x.frameHeader };
      }

      operations.push({
        key: `${method.toUpperCase()} ${path}`,
        method,
        path,
        operationId: op.operationId,
        summary: op.summary,
        description: op.description,
        security: op.security,
        params: pathParams,
        query: [...all.values()].filter((prm) => prm.in === 'query'),
        request,
        responses,
        socket,
        pointer: p,
      });
    }
  }
  // An unused component would be checked by nothing and could keep an otherwise unused definition in use.
  for (const kind of ['parameters', 'responses']) {
    for (const name of Object.keys(components[kind] ?? {})) {
      if (!used.has(`${kind}/${name}`)) fail(ptr('/components', kind, name), `components.${kind}.${name} is used by no operation`);
    }
  }
  return { operations, entry };
}

/** The TypeScript type of a body: a JSON body's type, any other's media type as a string literal, `null` for none. */
function bodyType(content, ctx, level) {
  if (content.length === 0) return atom('null');
  return union(content.map(({ media, schema, pointer }) =>
    isJsonMedia(media) ? conv(schema, level, ctx, ptr(pointer, 'schema')) : atom(JSON.stringify(media))));
}

function paramsType(list, ctx, level) {
  if (list.length === 0) return '{ [key: string]: never }';
  const pad = '  '.repeat(level + 1);
  const lines = list.map((prm) => {
    const doc = docBlock({ description: prm.description }, level + 1);
    return `${doc}${pad}${propKey(prm.name)}${prm.required ? '' : '?'}: ${conv(prm.schema, level + 1, ctx, ptr(prm.pointer, 'schema')).s};`;
  });
  return `{\n${lines.join('\n')}\n${'  '.repeat(level)}}`;
}

const API_OPERATIONS_DOC = [
  'The engine API\'s requests (openapi.json), by `METHOD /path`: each with its path parameters (`params`), its query',
  'parameters (`query`), its request body (`request`) and its responses by status. A JSON body is its type, any other',
  'body is named by its media type, and `null` is no body; `never` is no request body. A HEAD response has no body, so',
  'each is `null` (openapi.json\'s media types describe its headers).',
];

function apiOperations(operations, ctx) {
  const lines = [`/**\n${API_OPERATIONS_DOC.map((l) => ` * ${l}`).join('\n')}\n */`, 'export interface ApiOperations {'];
  for (const op of operations) {
    const summary = [op.operationId + (op.summary ? `: ${op.summary}` : ''), ...(op.description ? ['', op.description] : [])].join('\n');
    lines.push(docBlock({ description: summary }, 1) + `  ${propKey(op.key)}: {`);
    lines.push(`    params: ${paramsType(op.params, ctx, 2)};`);
    lines.push(`    query: ${paramsType(op.query, ctx, 2)};`);
    if (op.request === null) lines.push('    request: never;');
    else lines.push(`${docBlock({ description: op.request.description }, 2)}    request${op.request.required ? '' : '?'}: ${bodyType(op.request.content, ctx, 2).s};`);
    lines.push('    responses: {');
    for (const r of [...op.responses].sort((a, b) => a.status - b.status)) {
      const body = op.method === 'head' ? atom('null') : bodyType(r.content, ctx, 3);
      lines.push(`${docBlock({ description: r.description }, 3)}      ${r.status}: ${body.s};`);
    }
    lines.push('    };');
    lines.push('  };');
  }
  lines.push('}');
  return lines.join('\n');
}

